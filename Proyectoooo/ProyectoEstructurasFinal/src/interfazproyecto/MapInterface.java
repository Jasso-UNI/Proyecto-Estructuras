    /**
     * Crea el mapa con GraphStream a partir del grafo en memoria (InterfazProyecto.grafo)
     * y lo coloca en la ventana en lugar del texto "AQUÍ VA EL GRAFO DEL MAPA". Los botones
     * del diseño (Atrás, Archivo, Gestor de Red y Calcular Ruta) se conservan en una barra superior.
     */
    private void crearMapa() {
        System.setProperty("org.graphstream.ui", "swing");
        org.graphstream.graph.Graph gs = new org.graphstream.graph.implementations.SingleGraph("Mapa");
        gs.setAttribute("ui.stylesheet", CSS);
        gs.setAttribute("ui.antialias");
        gs.setAttribute("ui.quality");
        dibujarRed(gs);

        viewer = new org.graphstream.ui.swing_viewer.SwingViewer(gs,
                org.graphstream.ui.view.Viewer.ThreadingModel.GRAPH_IN_GUI_THREAD);
        viewer.enableAutoLayout();
        org.graphstream.ui.swing_viewer.ViewPanel vista =
                (org.graphstream.ui.swing_viewer.ViewPanel) viewer.addDefaultView(false);

        // Distribución: botones arriba y el mapa ocupando el resto de la ventana
        java.awt.Container cp = getContentPane();
        cp.removeAll();
        cp.setLayout(new java.awt.BorderLayout(6, 6));
        ((javax.swing.JComponent) cp).setBorder(javax.swing.BorderFactory.createEmptyBorder(8, 8, 8, 8));
        javax.swing.JPanel izq = new javax.swing.JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.LEFT, 6, 0));
        izq.add(btnAtras);
        javax.swing.JPanel der = new javax.swing.JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.RIGHT, 6, 0));
        der.add(btnArchivo);
        der.add(btnRed);
        der.add(btnRutas);
        javax.swing.JPanel barra = new javax.swing.JPanel(new java.awt.BorderLayout());
        barra.add(izq, java.awt.BorderLayout.WEST);
        barra.add(der, java.awt.BorderLayout.EAST);
        cp.add(barra, java.awt.BorderLayout.NORTH);
        cp.add(vista, java.awt.BorderLayout.CENTER);
        setMinimumSize(new java.awt.Dimension(900, 600));
        setSize(1200, 780);
    }

    /**
     * Copia el grafo propio a GraphStream: un nodo por estación (color según su subred,
     * calculada con DFS) y una arista por conexión (etiquetada con los minutos). También
     * marca la ruta, los hubs y el recorrido DFS que dejaron las pantallas de Rutas.
     *
     * @param gs grafo de GraphStream donde se dibuja
     */
    private void dibujarRed(org.graphstream.graph.Graph gs) {
        Grafo g = InterfazProyecto.grafo;
        int lim = g.getLimite();
        int[] comp = Conectividad.componentes(g);   // subred de cada estación (DFS)
        RecorridoDFS dfs = InterfazProyecto.dfsResaltado;
        Lista<Estacion> ruta = InterfazProyecto.rutaResaltada;
        Lista<Estacion> hubs = InterfazProyecto.hubsResaltados;

        boolean[] enRuta = new boolean[lim];
        boolean[] esHub = new boolean[lim];
        if (ruta != null) {
            for (int k = 0; k < ruta.tamano(); k++) {
                enRuta[ruta.obtener(k).getIndice()] = true;
            }
        }
        if (hubs != null) {
            for (int k = 0; k < hubs.tamano(); k++) {
                esHub[hubs.obtener(k).getIndice()] = true;
            }
        }

        for (int i = 0; i < lim; i++) {
            Estacion e = g.estacionEn(i);
            if (e == null) {
                continue;
            }
            org.graphstream.graph.Node n = gs.addNode(e.getId());
            String etiqueta = e.getId();
            if (dfs != null && dfs.getPosicion(i) >= 0) {
                etiqueta += " [" + (dfs.getPosicion(i) + 1) + "]";   // orden de visita del DFS
            }
            n.setAttribute("ui.label", etiqueta);
            int tam = 14 + Math.min(g.grado(i), 6) * 2;
            String borde = "#37474F";
            int ancho = 1;
            if (enRuta[i]) {
                borde = "#E53935";
                ancho = 4;
            }
            if (esHub[i]) {
                borde = "#FF9800";
                ancho = 5;
                tam += 6;
            }
            n.setAttribute("ui.style", "size: " + tam + "px; fill-color: " + PALETA[comp[i] % PALETA.length]
                    + "; stroke-mode: plain; stroke-color: " + borde + "; stroke-width: " + ancho + "px;");
        }

        for (int i = 0; i < lim; i++) {
            if (g.estacionEn(i) == null) {
                continue;
            }
            Lista<Arista> vec = g.vecinos(i);
            for (int k = 0; k < vec.tamano(); k++) {
                Arista a = vec.obtener(k);
                int j = a.getDestino();
                if (i > j) {
                    continue;
                }
                org.graphstream.graph.Edge ed = gs.addEdge(i + "-" + j, g.estacionEn(i).getId(), g.estacionEn(j).getId());
                ed.setAttribute("ui.label", String.valueOf(a.getTiempo()));
                if (aristaEnRuta(ruta, i, j)) {
                    ed.setAttribute("ui.style", "fill-color: #E53935; size: 5px;");
                } else if (dfs != null && (dfs.getPadre(j) == i || dfs.getPadre(i) == j)) {
                    ed.setAttribute("ui.style", "fill-color: #1E88E5; size: 4px;");   // arista del árbol DFS
                }
            }
        }
    }

    /**
     * Indica si la ruta pasa directamente de una estación a otra.
     *
     * @param ruta estaciones de la ruta en orden (puede ser null)
     * @param a índice de una estación
     * @param b índice de la otra estación
     * @return true si son consecutivas en la ruta
     */
    private boolean aristaEnRuta(Lista<Estacion> ruta, int a, int b) {
        if (ruta == null) {
            return false;
        }
        for (int k = 0; k + 1 < ruta.tamano(); k++) {
            int x = ruta.obtener(k).getIndice();
            int y = ruta.obtener(k + 1).getIndice();
            if ((x == a && y == b) || (x == b && y == a)) {
                return true;
            }
        }
        return false;
    }

