    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // jComboBox2 = Est. A, jComboBox1 = Est. B, jTextField1 = Tiempo
        Grafo g = InterfazProyecto.grafo;
        String idA = InterfazProyecto.idDeEtiqueta(jComboBox2.getSelectedItem());
        String idB = InterfazProyecto.idDeEtiqueta(jComboBox1.getSelectedItem());
        if (idA == null || idB == null) {
            aviso("La red no tiene estaciones.");
            return;
        }
        if (idA.equals(idB)) {
            aviso("Seleccione dos estaciones distintas.");
            return;
        }
        String tTxt = jTextField1.getText().trim();
        int tiempo;
        try {
            tiempo = Integer.parseInt(tTxt);
            if (tiempo <= 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException ex) {
            aviso("El tiempo debe ser un número entero mayor que 0.");
            return;
        }
        if (g.existeConexion(idA, idB)) {
            aviso("Ya existe una conexión entre " + idA + " y " + idB + ".\nElimínela primero si desea cambiar su tiempo.");
            return;
        }
        g.agregarConexion(idA, idB, tiempo);
        InterfazProyecto.cambios = true;
        InterfazProyecto.limpiarResaltados();
        JOptionPane.showMessageDialog(this, "Conexión " + idA + " - " + idB + " (" + tiempo + " min) agregada.",
                "Conexión agregada", JOptionPane.INFORMATION_MESSAGE);
        this.dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

