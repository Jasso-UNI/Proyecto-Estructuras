    /**
     * Guarda la red en el archivo fuente actual; si no hay uno, pide dónde guardarla.
     *
     * @return true si se guardó correctamente
     */
    private boolean guardarActual() {
        File destino = InterfazProyecto.archivoActual;
        if (destino == null) {
            JFileChooser selector = new JFileChooser();
            selector.setDialogTitle("Guardar red como");
            selector.setFileFilter(new FileNameExtensionFilter("Archivos CSV (*.csv)", "csv"));
            selector.setSelectedFile(new File("red_transporte.csv"));
            if (selector.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) {
                return false;
            }
            destino = selector.getSelectedFile();
            if (destino.getName().indexOf('.') < 0) {
                destino = new File(destino.getParentFile(), destino.getName() + ".csv");
            }
        }
        if (InterfazProyecto.grafo.numEstaciones() == 0) {
            int r = JOptionPane.showConfirmDialog(this, "La red está vacía: el archivo '" + destino.getName()
                    + "' quedará sin datos.\n¿Desea continuar?", "Red vacía",
                    JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (r != JOptionPane.YES_OPTION) {
                return false;
            }
        }
        try {
            EscritorCSV.guardar(destino, InterfazProyecto.grafo);
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo guardar el archivo:\n" + ex.getMessage(),
                    "Error al guardar", JOptionPane.ERROR_MESSAGE);
            return false;
        }
        InterfazProyecto.archivoActual = destino;
        InterfazProyecto.cambios = false;
        JOptionPane.showMessageDialog(this, "Datos guardados en '" + destino.getName() + "'.\nEstaciones: "
                + InterfazProyecto.grafo.numEstaciones() + "   Conexiones: " + InterfazProyecto.grafo.numConexiones(),
                "Guardado", JOptionPane.INFORMATION_MESSAGE);
        return true;
    }

