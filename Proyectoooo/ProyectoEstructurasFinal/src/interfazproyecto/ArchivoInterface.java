    private void abrirMapaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_abrirMapaActionPerformed
        // Cargar: alerta de sobrescritura, selección con JFileChooser y carga del CSV en el grafo y la hash
        if (InterfazProyecto.grafo.numEstaciones() > 0 || InterfazProyecto.cambios) {
            String[] opciones = {"Guardar y continuar", "Continuar sin guardar", "Cancelar"};
            int r = JOptionPane.showOptionDialog(this,
                    "Al cargar un nuevo archivo se sobrescribirán los datos que están en memoria.\n"
                  + (InterfazProyecto.cambios ? "Hay cambios sin guardar.\n" : "")
                  + "Se recomienda guardar antes de continuar.",
                    "Atención: se sobrescribirán los datos", JOptionPane.DEFAULT_OPTION,
                    JOptionPane.WARNING_MESSAGE, null, opciones, opciones[InterfazProyecto.cambios ? 0 : 1]);
            if (r == 0) {
                if (!guardarActual()) {
                    return;
                }
            } else if (r != 1) {
                return;   // cancelar
            }
        }
        JFileChooser selector = new JFileChooser();
        selector.setDialogTitle("Seleccione un archivo CSV");
        selector.setFileFilter(new FileNameExtensionFilter("Archivos CSV / texto (*.csv, *.txt)", "csv", "txt"));
        File carpetaData = new File("data");
        if (carpetaData.isDirectory()) {
            selector.setCurrentDirectory(carpetaData);
        }
        if (selector.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;
        }
        File archivo = selector.getSelectedFile();
        try {
            Grafo nuevo = new Grafo();
            ReporteCarga rep = LectorCSV.cargarArchivo(archivo, nuevo);
            if (nuevo.numEstaciones() == 0) {
                JOptionPane.showMessageDialog(this, "El archivo no contiene estaciones ni conexiones válidas.\n"
                        + "Se conservaron los datos actuales.", "Archivo sin datos", JOptionPane.WARNING_MESSAGE);
                return;
            }
            InterfazProyecto.grafo = nuevo;
            InterfazProyecto.archivoActual = archivo;
            InterfazProyecto.cambios = false;
            InterfazProyecto.limpiarResaltados();
            String resumen = "Archivo: " + archivo.getName() + "\nEstaciones: " + rep.getEstacionesAgregadas()
                    + "\nConexiones: " + rep.getConexionesAgregadas();
            if (rep.getLineasInvalidas() > 0) {
                JOptionPane.showMessageDialog(this, resumen + "\n\nLíneas ignoradas por errores: "
                        + rep.getLineasInvalidas() + "\n" + rep.getDetalle(), "Carga con advertencias",
                        JOptionPane.WARNING_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, resumen, "Archivo cargado", JOptionPane.INFORMATION_MESSAGE);
            }
            // Mostrar el mapa con la red cargada
            MapInterface ventanaMapa = new MapInterface();
            ventanaMapa.setLocationRelativeTo(null);
            ventanaMapa.setVisible(true);
            this.dispose();
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo leer el archivo:\n" + ex.getMessage(),
                    "Error de lectura", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_abrirMapaActionPerformed

