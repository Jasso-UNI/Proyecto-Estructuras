    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // OK: confirma y cierra (elimina) la estación elegida del grafo y de la tabla hash
        String id = InterfazProyecto.idDeEtiqueta(jComboBox1.getSelectedItem());
        if (id == null) {
            JOptionPane.showMessageDialog(this, "No hay estaciones para cerrar.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        java.awt.Frame padre = (java.awt.Frame) javax.swing.SwingUtilities.getWindowAncestor(this);
        ConfirmInterface ventanaConfirmacion = new ConfirmInterface(padre, true);
        ventanaConfirmacion.setLocationRelativeTo(this);
        ventanaConfirmacion.setVisible(true);
        if (ventanaConfirmacion.isConfirmado() == true){
            Grafo g = InterfazProyecto.grafo;
            int antes = Conectividad.contar(Conectividad.componentes(g));
            g.eliminarEstacion(id);
            int despues = Conectividad.contar(Conectividad.componentes(g));
            InterfazProyecto.cambios = true;
            InterfazProyecto.limpiarResaltados();
            JOptionPane.showMessageDialog(this, "Estación " + id + " cerrada.\nSubredes: " + antes + " -> " + despues
                    + (despues > antes ? "\nEl cierre dejó zonas incomunicadas." : ""),
                    "Estación cerrada", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

