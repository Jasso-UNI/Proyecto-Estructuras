    /** Reemplaza el texto de ejemplo por las instrucciones de uso del programa. */
    private void mostrarAyuda() {
        jLabel1.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 16));
        jLabel1.setText("<html><body style='width:640px'>"
            + "<h2>Cómo usar UrbanRoute</h2>"
            + "<b>Mapa:</b> dibuja la red en memoria. El número sobre cada conexión son los minutos de traslado. "
            + "Cada subred conectada tiene su propio color y las estaciones aisladas se ven como puntos sueltos. "
            + "Puede arrastrar los nodos para acomodarlos.<br><br>"
            + "<b>Archivo:</b> <i>Cargar</i> reemplaza la red por un archivo CSV (avisa antes de sobrescribir los datos). "
            + "<i>Guardar</i> actualiza el archivo fuente con los cambios hechos.<br><br>"
            + "<b>Gestión de Red:</b> agregar una estación con sus conexiones (formato <i>ID:minutos</i>, por ejemplo PRO:2, PER:3), "
            + "agregar o eliminar una conexión y cerrar una estación. El mapa se actualiza al volver.<br><br>"
            + "<b>Rutas:</b> <i>Calcular</i> halla el trayecto de menor tiempo entre dos estaciones; "
            + "<i>Subredes</i> detecta con DFS los sectores que quedan aislados y numera en el mapa el orden del recorrido; <i>Hubs</i> muestra las estaciones con más conexiones. "
            + "Al volver al mapa la ruta o los hubs quedan resaltados."
            + "</body></html>");
        pack();
    }

