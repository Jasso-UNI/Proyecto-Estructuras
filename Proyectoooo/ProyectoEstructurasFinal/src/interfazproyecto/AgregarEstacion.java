    /** Selecciona el texto al enfocar cada campo, para reemplazar el texto de ejemplo "escriba aquí...". */
    private void prepararCampos() {
        javax.swing.JTextField[] campos = {jTextField1, jTextField2, jTextField3, jTextField4};
        for (int i = 0; i < campos.length; i++) {
            campos[i].addFocusListener(new java.awt.event.FocusAdapter() {
                @Override
                public void focusGained(java.awt.event.FocusEvent e) {
                    ((javax.swing.JTextField) e.getSource()).selectAll();
                }
            });
        }
    }

    /**
     * Texto de un campo, tratando como vacío el texto de ejemplo "escriba aquí...".
     *
     * @param campo campo de texto
     * @return texto sin espacios en los extremos (vacío si es el texto de ejemplo)
     */
    private static String texto(javax.swing.JTextField campo) {
        String t = campo.getText().trim();
        return t.toLowerCase().startsWith("escriba aqu") ? "" : t;
    }

    private void aviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Aviso", JOptionPane.WARNING_MESSAGE);
    }

