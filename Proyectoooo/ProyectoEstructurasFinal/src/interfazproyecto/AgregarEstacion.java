    private void btnOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOkActionPerformed
        // Campos: jTextField2 = ID, jTextField1 = Nombre, jTextField4 = Pas/h, jTextField3 = Conexiones
        Grafo g = InterfazProyecto.grafo;
        String id = texto(jTextField2).toUpperCase();
        String nombre = texto(jTextField1);
        String capTxt = texto(jTextField4);
        String conTxt = texto(jTextField3);

        // Se valida todo ANTES de modificar la red, para no dejar una estación a medias
        if (id.isEmpty() || id.indexOf(',') >= 0 || id.indexOf(';') >= 0 || id.indexOf(':') >= 0) {
            aviso("El ID es obligatorio y no puede contener comas, punto y coma ni dos puntos.");
            return;
        }
        if (g.buscarEstacion(id) != null) {
            aviso("Ya existe una estación con el ID '" + id + "'.");
            return;
        }
        int capacidad = 0;
        if (!capTxt.isEmpty()) {
            try {
                capacidad = Integer.parseInt(capTxt);
                if (capacidad < 0) {
                    throw new NumberFormatException();
                }
            } catch (NumberFormatException ex) {
                aviso("Los pasajeros por hora deben ser un número entero mayor o igual a 0.");
                return;
            }
        }
        Lista<String> vecinos = new Lista<String>();
        Lista<Integer> tiempos = new Lista<Integer>();
        if (!conTxt.isEmpty()) {
            String[] items = conTxt.split("[,;\\r\\n]+");
            for (int i = 0; i < items.length; i++) {
                String item = items[i].trim();
                if (item.isEmpty()) {
                    continue;
                }
                String[] partes = item.split("[:=\\s]+");
                if (partes.length != 2) {
                    aviso("Conexión inválida: '" + item + "'.\nUse el formato ID:minutos (ej. PRO:2, PER:3).");
                    return;
                }
                String vid = partes[0].trim().toUpperCase();
                if (g.buscarEstacion(vid) == null) {
                    aviso("La estación '" + vid + "' de las conexiones no existe en la red.");
                    return;
                }
                if (vid.equals(id)) {
                    aviso("Una estación no puede conectarse consigo misma.");
                    return;
                }
                for (int k = 0; k < vecinos.tamano(); k++) {
                    if (vecinos.obtener(k).equals(vid)) {
                        aviso("La estación '" + vid + "' está repetida en las conexiones.");
                        return;
                    }
                }
                try {
                    int t = Integer.parseInt(partes[1]);
                    if (t <= 0) {
                        throw new NumberFormatException();
                    }
                    vecinos.agregar(vid);
                    tiempos.agregar(Integer.valueOf(t));
                } catch (NumberFormatException ex) {
                    aviso("El tiempo de '" + item + "' debe ser un entero mayor que 0.");
                    return;
                }
            }
        }

        // Todo es válido: se agrega a la vez al grafo y a la tabla hash
        g.agregarEstacion(new Estacion(id, nombre.isEmpty() ? id : nombre, "Sin línea", "Sin zona", capacidad));
        for (int k = 0; k < vecinos.tamano(); k++) {
            g.agregarConexion(id, vecinos.obtener(k), tiempos.obtener(k).intValue());
        }
        InterfazProyecto.cambios = true;
        InterfazProyecto.limpiarResaltados();
        JOptionPane.showMessageDialog(this, "Estación " + id + " agregada con " + vecinos.tamano()
                + " conexión(es).", "Estación agregada", JOptionPane.INFORMATION_MESSAGE);
        this.dispose();
    }//GEN-LAST:event_btnOkActionPerformed

