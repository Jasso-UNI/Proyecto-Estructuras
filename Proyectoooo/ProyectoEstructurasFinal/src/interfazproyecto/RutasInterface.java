    private void btnAtrasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtrasActionPerformed
        // Calcular: ruta de menor tiempo con Dijkstra entre el origen y el destino elegidos
        String origen = InterfazProyecto.idDeEtiqueta(this.idOrigen.getSelectedItem());
        String destino = InterfazProyecto.idDeEtiqueta(this.idDestino.getSelectedItem());
        if (origen == null || destino == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "La red no tiene estaciones para calcular una ruta.",
                    "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (origen.equals(destino)) {
            javax.swing.JOptionPane.showMessageDialog(this, "El origen y el destino son la misma estación (0 min).",
                    "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        Grafo g = InterfazProyecto.grafo;
        ResultadoRuta res = RutaOptima.calcular(g, origen, destino);
        InterfazProyecto.limpiarResaltados();
        if (!res.isExiste()) {
            mostrarResultado("<b>SIN RUTA</b><br>" + esc(origen) + " &rarr; " + esc(destino) + "<br><br>" + esc(res.getMotivo()));
            return;
        }
        Lista<Estacion> camino = res.getCamino();
        int cambiosLinea = 0;
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < camino.tamano(); i++) {
            Estacion e = camino.obtener(i);
            if (i > 0 && !e.getLinea().equals(camino.obtener(i - 1).getLinea())) {
                cambiosLinea++;
            }
            sb.append(i > 0 ? " &rarr; " : "").append(esc(e.getId()));
        }
        InterfazProyecto.rutaResaltada = camino;   // el mapa la resalta al volver
        mostrarResultado("<b>RUTA MÁS RÁPIDA</b><br>" + esc(g.buscarEstacion(origen).toString()) + " &rarr; "
                + esc(g.buscarEstacion(destino).toString()) + "<br><br>"
                + "Tiempo total: <b>" + res.getTiempoTotal() + " min</b><br>"
                + "Estaciones: " + camino.tamano() + "<br>"
                + "Cambios de línea: " + cambiosLinea + "<br><br>"
                + "Recorrido:<br>" + sb);
    }//GEN-LAST:event_btnAtrasActionPerformed

