    private void btnAtras2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtras2ActionPerformed
        // Subredes: detección de componentes conexos con DFS (recorrido en profundidad)
        Grafo g = InterfazProyecto.grafo;
        if (g.numEstaciones() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "La red no tiene estaciones que analizar.",
                    "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        RecorridoDFS r = Conectividad.dfsTodo(g);
        InterfazProyecto.limpiarResaltados();
        InterfazProyecto.dfsResaltado = r;   // el mapa muestra el orden del DFS al volver
        int[] tam = Conectividad.tamanos(Conectividad.componentes(g));
        StringBuilder sb = new StringBuilder("<b>SUBREDES (DFS)</b><br>Total: " + r.getNumComponentes() + "<br>");
        sb.append(r.getNumComponentes() == 1 ? "Toda la red está conectada." : "Hay zonas incomunicadas entre sí.");
        for (int k = 0; k < r.getCantidad(); k++) {
            int i = r.getOrden(k);
            if (k == 0 || r.getComp(i) != r.getComp(r.getOrden(k - 1))) {
                int c = r.getComp(i);
                sb.append("<br><br><b>Subred ").append(c + 1).append("</b> (").append(tam[c])
                  .append(tam[c] == 1 ? " estación" : " estaciones").append("):<br>");
            } else {
                sb.append(" &rarr; ");
            }
            sb.append(esc(g.estacionEn(i).getId()));
        }
        mostrarResultado(sb.toString());
    }//GEN-LAST:event_btnAtras2ActionPerformed

    private void btnAtras3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtras3ActionPerformed
        // Hubs: estaciones de mayor grado (centralidad de grado)
        Grafo g = InterfazProyecto.grafo;
        Lista<Estacion> hubs = Hubs.hubs(g);
        if (g.numEstaciones() == 0 || hubs.estaVacia()) {
            javax.swing.JOptionPane.showMessageDialog(this, "La red no tiene conexiones, por lo que no hay hubs.",
                    "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        InterfazProyecto.limpiarResaltados();
        InterfazProyecto.hubsResaltados = hubs;   // el mapa los resalta al volver
        StringBuilder sb = new StringBuilder("<b>HUBS DE TRANSFERENCIA</b><br>Grado máximo: " + Hubs.gradoMaximo(g)
                + " conexiones directas<br><br>Hub(s) principal(es):<br>");
        for (int i = 0; i < hubs.tamano(); i++) {
            sb.append("&bull; ").append(esc(hubs.obtener(i).toString())).append(" (")
              .append(esc(hubs.obtener(i).getLinea())).append(")<br>");
        }
        Lista<Estacion> rank = Hubs.ranking(g, 5);
        sb.append("<br>Top 5 por grado:<br>");
        for (int i = 0; i < rank.tamano(); i++) {
            sb.append(i + 1).append(". ").append(esc(rank.obtener(i).toString())).append(" - grado ")
              .append(g.grado(rank.obtener(i).getIndice())).append("<br>");
        }
        mostrarResultado(sb.toString());
    }//GEN-LAST:event_btnAtras3ActionPerformed

 

    /**
     * Muestra un texto en el área RESULTADO (la etiqueta jLabel4 del diseño).
     *
     * @param html contenido en HTML sencillo
     */
    private void mostrarResultado(String html) {
        jLabel4.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 15));
        jLabel4.setText("<html><body style='width:560px'>" + html + "</body></html>");
        pack();
    }

    /**
     * Escapa los caracteres especiales de HTML de un texto.
     *
     * @param t texto original
     * @return texto seguro para mostrar dentro de la etiqueta
     */
    private static String esc(String t) {
        return t == null ? "" : t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }

